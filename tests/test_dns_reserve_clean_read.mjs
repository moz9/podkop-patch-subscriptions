import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../openwrt/dns_benchmark.js',import.meta.url),'utf8');
const body=source.slice(source.indexOf('  function reconcileReserveFields('),source.indexOf('  function showReserveStatus('));
assert.ok(body.includes('function reconcileReserveFields'));
const saved={enabled:true,dnsType:'dot',dnsServer:'dns.google',bootstrapDnsType:'udp',bootstrapDnsServer:'77.88.8.8'};
const baseline={secondary_dns_enabled:'1',secondary_dns_type:'dot',secondary_dns_server:'dns.google',secondary_bootstrap_dns_type:'udp',secondary_bootstrap_dns_server:'77.88.8.8'};
let changes=0;
const options=new Map(Object.entries(baseline).map(([name,value])=>{
 const o={value,current:value,dirty:false,cfgvalue(sid,next){if(arguments.length===2)this.value=next;return this.value;},formvalue(){return this.current;},getUIElement(){return {node:{getAttribute:()=>o.dirty?'true':null,removeAttribute:()=>{o.dirty=false;}},setValue:next=>{changes++;o.current=next;o.dirty=true;}};}};
 return [name,o];
}));
const context={map:{lookupOption:name=>[options.get(name)]},uci:{state:{values:{podkop:{settings:{...baseline}}},changes:{},deletes:{}}}};
vm.createContext(context);vm.runInContext(body+';this.reconcile=reconcileReserveFields;',context);
context.reconcile(saved);
assert.equal(changes,0,'read-only status must not call LuCI setValue for unchanged fields: it emits change and blocks DNS apply');
context.reconcile(saved);
assert.equal(changes,0,'repeated read remains clean');
options.get('secondary_dns_server').current='my-draft.example';
context.reconcile(saved);
assert.equal(options.get('secondary_dns_server').current,'my-draft.example','real browser draft is preserved');
assert.equal(changes,0,'read does not rewrite real draft');
options.get('secondary_dns_server').current='dns.google';
options.get('secondary_dns_server').dirty=true;
context.reconcile({...saved,dnsServer:'dns.new.example'});
assert.equal(options.get('secondary_dns_server').current,'dns.google','existing native dirty marker is respected even when value matches baseline');
assert.equal(options.get('secondary_dns_server').dirty,true,'user marker is not cleared');
options.get('secondary_dns_server').dirty=false;
context.reconcile({...saved,dnsServer:'dns.new.example'});
assert.equal(options.get('secondary_dns_server').current,'dns.new.example','clean field follows changed persisted reserve');
assert.equal(options.get('secondary_dns_server').dirty,false,'synchronous readback does not become a user edit');
assert.equal(options.get('secondary_dns_server').value,'dns.new.example','form baseline is rebased with the value');
console.log('PASS: reserve status does not dirty unchanged LuCI fields or overwrite actual drafts');
